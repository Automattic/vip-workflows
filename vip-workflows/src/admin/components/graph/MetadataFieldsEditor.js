/**
 * MetadataFieldsEditor — editorial metadata fields for a sequence.
 *
 * A sequence's metadata fields are an ordered list of named, typed places to put
 * a value, so they are an `InspectorFieldList`, and all that lives here is what
 * makes a metadata field a metadata field: its type options, its config form,
 * and what a new one starts as.
 *
 * That replaces a stack of `Card`s, one open sub-form per field, which turned a
 * sequence carrying half a dozen fields into a wall of controls with no way to
 * see the list's shape — and which had no order at all, since nothing offered to
 * change it. The list is now the surface, one field's options open at a time,
 * and the order is the author's to drag.
 *
 * @package
 */

import {
	TextControl,
	TextareaControl,
	SelectControl,
	ToggleControl,
} from '@wordpress/components';
import { Stack } from '@wordpress/ui';
import { __ } from '@wordpress/i18n';
import { sanitizeMetadataKey } from '../../utils/metadata-keys';
import InspectorFieldList, {
	InspectorFieldListAdd,
} from './InspectorFieldList';

const FIELD_TYPES = [
	{ label: __( 'Text', 'vip-workflows' ), value: 'text' },
	{ label: __( 'Text area', 'vip-workflows' ), value: 'textarea' },
	{ label: __( 'Select', 'vip-workflows' ), value: 'select' },
	{ label: __( 'Date', 'vip-workflows' ), value: 'date' },
	{ label: __( 'User', 'vip-workflows' ), value: 'user' },
];

/**
 * Name a field's type, including one this build cannot author.
 *
 * A type registered by an extension, or one a newer version wrote, still has to
 * read back as itself in the list rather than as a blank.
 *
 * @param {string} type The field's stored type.
 * @return {string} A human-readable name for it.
 */
function fieldTypeLabel( type ) {
	return FIELD_TYPES.find( ( t ) => t.value === type )?.label || type;
}

/**
 * The key a label change implies.
 *
 * The key follows the label until someone types a key of their own; from then on
 * it is theirs and renaming the field leaves it alone.
 *
 * @param {Object} field The field being renamed.
 * @param {string} label Its new label.
 * @return {string} The key the field should now carry.
 */
function keyForLabelChange( field, label ) {
	if ( field.keyAutoGenerated === false ) {
		return field.key || '';
	}
	if ( field.keyAutoGenerated || ! field.key ) {
		return sanitizeMetadataKey( label );
	}
	return field.key;
}

/**
 * A new metadata field.
 *
 * Deliberately blank rather than pre-named. The key is generated from the label,
 * so there is nothing to auto-generate until the author has said what the field
 * is — and `InspectorFieldList` will not flag an unnamed row as missing its key
 * for exactly that reason.
 *
 * @return {Object} The new field.
 */
function createField() {
	return {
		key: '',
		label: '',
		type: 'text',
		required: false,
		searchable: false,
		keyAutoGenerated: true,
	};
}

/**
 * The Add control for the metadata field list, for a section's `actions` slot.
 *
 * @param {Object}   props          Component props.
 * @param {Array}    props.fields   The current fields.
 * @param {Function} props.onChange Reports the whole list back.
 * @return {JSX.Element} The add control.
 */
export function MetadataFieldsAdd( { fields, onChange } ) {
	return (
		<InspectorFieldListAdd
			addOptions={ [
				{ label: __( 'Field', 'vip-workflows' ), value: 'field' },
			] }
			onAdd={ () => onChange( [ ...fields, createField() ] ) }
			label={ __( 'Add field', 'vip-workflows' ) }
		/>
	);
}

/**
 * What the Required toggle says under itself, and whether it can be changed.
 *
 * The server checks required fields at one moment only: a transition that
 * crosses into the publish region (`Sequence::crosses_into_publish()`) — from
 * a stage outside publish to a stage inside it. On a sequence with no such
 * transition that moment never comes, so marking a field required would
 * promise something nothing enforces. That includes a sequence that has
 * publish stages but never moves a post into them from outside: one whose
 * publish stages are reached only from each other, or not at all. The toggle
 * is disabled there, and says why.
 *
 * A field that is ALREADY stored as required on such a sequence is the one
 * exception. Its toggle reads back as on, because that is what is stored —
 * showing it off would misreport the data, and quietly writing it off would be
 * a repair nobody asked for. It stays switchable so the author can clear a
 * flag that does nothing, and its help says that it does nothing. Once it is
 * off, it is disabled like every other field on the sequence.
 *
 * @param {Object}  field                    The field being configured.
 * @param {boolean} hasTransitionIntoPublish Whether any transition takes the
 *                                           post into the publish region.
 * @return {{disabled: boolean, help: string}} The toggle's state and help.
 */
function requiredToggleState( field, hasTransitionIntoPublish ) {
	if ( hasTransitionIntoPublish ) {
		return {
			disabled: false,
			help: __(
				'Must have a value before a transition moves the post into Published.',
				'vip-workflows'
			),
		};
	}
	if ( field.required ) {
		return {
			disabled: false,
			help: __(
				'Never checked, because no transition here leads into Published.',
				'vip-workflows'
			),
		};
	}
	return {
		disabled: true,
		help: __(
			'Only checked on transitions into Published, and this sequence has none.',
			'vip-workflows'
		),
	};
}

/**
 * The sequence's metadata field list.
 *
 * @param {Object}   props                          Component props.
 * @param {Array}    props.fields                   The current fields.
 * @param {Function} props.onChange                 Reports the whole list back.
 * @param {boolean}  props.hasTransitionIntoPublish Whether any transition takes
 *                                                  the post into the publish
 *                                                  region — the only place
 *                                                  required fields are checked.
 * @return {JSX.Element} The field list.
 */
export default function MetadataFieldsEditor( {
	fields,
	onChange,
	hasTransitionIntoPublish,
} ) {
	return (
		<InspectorFieldList
			items={ fields }
			onChange={ onChange }
			keyOf={ ( field ) => field.key || '' }
			// A field the author has named is one they have started, so a key
			// they then cleared by hand is a state someone chose and Save will
			// refuse. A row added a moment ago and not yet typed into is
			// incomplete rather than wrong.
			isStarted={ ( field ) => Boolean( field.label ) }
			describe={ ( field ) => ( {
				label: field.label || __( 'Untitled', 'vip-workflows' ),
				value: fieldTypeLabel( field.type ),
			} ) }
			renderConfig={ ( { item: field, update, problem } ) => {
				const requiredToggle = requiredToggleState(
					field,
					hasTransitionIntoPublish
				);
				return (
					<>
						<TextControl
							__next40pxDefaultSize
							__nextHasNoMarginBottom
							label={ __( 'Field label', 'vip-workflows' ) }
							value={ field.label }
							onChange={ ( label ) =>
								update( {
									label,
									key: keyForLabelChange( field, label ),
								} )
							}
						/>
						<TextControl
							__next40pxDefaultSize
							__nextHasNoMarginBottom
							label={ __( 'Key', 'vip-workflows' ) }
							value={ field.key }
							onChange={ ( v ) =>
								update( {
									key: sanitizeMetadataKey( v ),
									keyAutoGenerated: false,
								} )
							}
							placeholder="content_pillar"
							className={
								problem ? 'wf-metadata-field__key--invalid' : ''
							}
							help={ problem?.full }
						/>
						<SelectControl
							__next40pxDefaultSize
							__nextHasNoMarginBottom
							label={ __( 'Type', 'vip-workflows' ) }
							value={ field.type }
							options={ FIELD_TYPES }
							onChange={ ( type ) => update( { type } ) }
						/>
						{ field.type === 'select' && (
							<TextareaControl
								__nextHasNoMarginBottom
								label={ __( 'Options', 'vip-workflows' ) }
								value={ ( field.options || [] ).join( '\n' ) }
								onChange={ ( v ) =>
									update( { options: v.split( '\n' ) } )
								}
								help={ __(
									'One option per line',
									'vip-workflows'
								) }
								rows={ 3 }
							/>
						) }
						{ /* A column rather than a row: Required carries a sentence
					     of help, which would wrap to a few words a line in half
					     the popover's width. */ }
						<Stack direction="column" gap="md" align="stretch">
							<ToggleControl
								__nextHasNoMarginBottom
								label={ __( 'Required', 'vip-workflows' ) }
								checked={ Boolean( field.required ) }
								onChange={ ( required ) =>
									update( { required } )
								}
								// The help is visible text tied to the input by
								// aria-describedby, so the reason stays readable,
								// and announced, while the toggle is disabled.
								disabled={ requiredToggle.disabled }
								help={ requiredToggle.help }
							/>
							<ToggleControl
								__nextHasNoMarginBottom
								label={ __( 'Searchable', 'vip-workflows' ) }
								checked={ Boolean( field.searchable ) }
								onChange={ ( searchable ) =>
									update( { searchable } )
								}
							/>
						</Stack>
					</>
				);
			} }
			removeLabel={ __( 'Remove field', 'vip-workflows' ) }
			emptyLabel={ __(
				'No fields yet. Add one to collect a value per post.',
				'vip-workflows'
			) }
		/>
	);
}
